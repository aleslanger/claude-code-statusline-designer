"""Write the rendered statusline script and wire it into Claude Code settings."""
from __future__ import annotations

import json
import os
import shutil
import tempfile
from pathlib import Path

from claude_style.render import render

CLAUDE_DIR = Path.home() / ".claude"
STATUSLINE_PATH = CLAUDE_DIR / "statusline-command.sh"
SETTINGS_PATH = CLAUDE_DIR / "settings.json"
SCRIPT_MODE = 0o755
PERMISSION_BITS = 0o777
HEADER_LINES_TO_CHECK = 3
# Header comments of scripts this tool generated (current and pre-rename).
GENERATED_MARKERS = ("# Generated by Claude Code Statusline Designer", "# Generated by claudeStyle")


class InstallError(RuntimeError):
    pass


def _backup_path() -> Path:
    return STATUSLINE_PATH.with_suffix(".sh.bak")


def _is_generated(path: Path) -> bool:
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            head = [next(f, "") for _ in range(HEADER_LINES_TO_CHECK)]
    except OSError as exc:
        raise InstallError(f"can't read {path}: {exc.strerror}") from None
    return any(line.startswith(GENERATED_MARKERS) for line in head)


def _read_settings() -> dict:
    if not SETTINGS_PATH.exists():
        return {}
    try:
        settings = json.loads(SETTINGS_PATH.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise InstallError(f"{SETTINGS_PATH} is not valid JSON ({exc}); fix it first, it was left untouched") from None
    except OSError as exc:
        raise InstallError(f"can't read {SETTINGS_PATH}: {exc.strerror}") from None
    if not isinstance(settings, dict):
        raise InstallError(f"{SETTINGS_PATH} must contain a JSON object; it was left untouched")
    return settings


def _atomic_write(path: Path, text: str, mode: int | None = None) -> None:
    """Write a temp file next to `path`, then rename it over `path`.

    Claude Code never sees a half-written file: a statusline run already in
    progress keeps the old one, the next run gets the new one whole.
    """
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.stem}-", suffix=path.suffix)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        if mode is not None:
            os.chmod(tmp, mode)
        os.replace(tmp, path)
    except OSError as exc:
        Path(tmp).unlink(missing_ok=True)
        raise InstallError(f"can't write {path}: {exc.strerror}") from None


def _write_settings(settings: dict) -> None:
    # Resolved, so a symlinked settings.json (dotfile managers) stays a link to the
    # updated file; its permissions are kept, since mkstemp would leave 0600.
    target = SETTINGS_PATH.resolve()
    mode = target.stat().st_mode & PERMISSION_BITS if target.exists() else None
    _atomic_write(target, json.dumps(settings, indent=2, ensure_ascii=False) + "\n", mode)


def install(config: dict) -> Path:
    script = render(config)
    settings = _read_settings()  # fail before touching anything if settings.json is broken

    try:
        CLAUDE_DIR.mkdir(parents=True, exist_ok=True)
        # Back up only a script someone else wrote; re-installing must never
        # overwrite the user's original with one of our own generated scripts.
        if STATUSLINE_PATH.exists() and not _is_generated(STATUSLINE_PATH):
            shutil.copyfile(STATUSLINE_PATH, _backup_path())
    except OSError as exc:
        raise InstallError(f"can't prepare {STATUSLINE_PATH}: {exc.strerror}") from None
    _atomic_write(STATUSLINE_PATH, script, SCRIPT_MODE)

    # Written even when unchanged: Claude Code re-runs the statusline when
    # settings.json changes, so a running session shows the new look at once.
    desired = {"type": "command", "command": str(STATUSLINE_PATH)}
    _write_settings({**settings, "statusLine": desired})
    return STATUSLINE_PATH


def uninstall() -> bool:
    """Remove the statusLine key from settings.json and restore the backup script, if any."""
    settings = _read_settings()
    removed_key = "statusLine" in settings
    if removed_key:
        _write_settings({k: v for k, v in settings.items() if k != "statusLine"})

    backup = _backup_path()
    if backup.exists():
        try:
            shutil.copyfile(backup, STATUSLINE_PATH)
        except OSError as exc:
            raise InstallError(f"can't restore {backup}: {exc.strerror}") from None
    return removed_key
